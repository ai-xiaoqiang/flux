/** 取某平台红线（含通用红线），platform 不匹配时只返回通用 */
export function getRedLines(platform?: string): string[] {
  const p = String(platform ?? "").trim();
  const all: string[] = [];
  for (const group of VIDEO_PLATFORM_RED_LINES) {
    if (group.platform === "通用" || group.platform === p) {
      all.push(...group.rules);
    }
  }
  return all;
}
